/**
 * Writes the "Motion per event" table in docs/13-automation-platform.md from the event-motion
 * catalogue (packages/shared/src/motion), between the motion:begin and motion:end markers.
 *   npm run build -w @mizan/shared && node packages/shared/scripts/gen-motion-docs.mjs
 * test/motion.test.ts fails when the committed table is not current.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const DOCS_PATH = join(dirname(fileURLToPath(import.meta.url)), "../../../docs/13-automation-platform.md");
export const BEGIN = "<!-- motion:begin (generated by packages/shared/scripts/gen-motion-docs.mjs; do not edit) -->";
export const END = "<!-- motion:end -->";

/** The markdown table: one row per domain event. Pure: the test calls it with the catalogue. */
export function renderMotionTable({ EVENT_MOTION }) {
  const rows = Object.entries(EVENT_MOTION).map(([type, r]) => {
    const branches = r.variant ? Object.entries(r.variant.outcomes) : [];
    const outcome = r.variant ? `${r.outcome}; by \`${r.variant.arg}\`: ${branches.map(([b, o]) => `${b} → ${o}`).join(", ")}` : r.outcome;
    const reds = r.variant ? branches.filter(([, o]) => o === "drop").map(([b]) => b) : r.outcome === "drop" ? ["always"] : [];
    const red = reds.length ? `yes (${reds.join(", ")})` : "no";
    return `| \`${type}\` | ${outcome} | ${r.action ?? "—"} | ${r.pending ?? "—"} | ${red} | ${r.surfaces.join(", ") || "—"} |`;
  });
  return [BEGIN, "| Event | Motion (outcome) | Action | While on its way | Red | Surfaces |", "| --- | --- | --- | --- | --- | --- |", ...rows, END].join("\n");
}

/** The docs file with its table replaced. */
export function withTable(doc, table) {
  const a = doc.indexOf(BEGIN), b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error("docs/13: motion markers not found");
  return doc.slice(0, a) + table + doc.slice(b + END.length);
}

if (process.argv[1]?.endsWith("gen-motion-docs.mjs")) {
  const m = await import("../dist/motion/index.js");
  writeFileSync(DOCS_PATH, withTable(readFileSync(DOCS_PATH, "utf8").replace(/\r\n/g, "\n"), renderMotionTable(m)));
  console.log(`wrote ${DOCS_PATH}`);
}
