import type { MigrationClient } from "./migrate.js";

/**
 * Generates Kysely table types (src/schema.ts) from the migrated database.
 * SQL migrations stay the single source of truth (ADR-0012).
 */

interface ColumnRow {
  table_name: string;
  column_name: string;
  udt_name: string;
  is_nullable: "YES" | "NO";
  column_default: string | null;
  is_identity: "YES" | "NO";
  is_generated: "ALWAYS" | "NEVER";
}

const SCALARS: Record<string, string> = {
  uuid: "string", text: "string", varchar: "string", bpchar: "string", citext: "string", inet: "string", name: "string",
  int2: "number", int4: "number", float4: "number", float8: "number",
  int8: "Int8", numeric: "Numeric",
  bool: "boolean",
  timestamptz: "Timestamp", timestamp: "Timestamp", date: "Timestamp",
  jsonb: "Json", json: "Json",
  bytea: "Buffer",
  interval: "string", time: "string", timetz: "string",
};

function tsType(udt: string): string {
  if (udt.startsWith("_")) return `ArrayType<${tsType(udt.slice(1))}>`;
  return SCALARS[udt] ?? "unknown";
}

const pascal = (s: string) => s.replace(/(^|_)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());

const HEADER = `/**
 * GENERATED by \`npm run codegen -w @mizan/db\` from packages/db/migrations.
 * Do not edit by hand: add a migration and re-run codegen
 * (test/codegen.test.ts fails when this file is stale).
 */

import type { ColumnType } from "kysely";

export type Generated<T> = T extends ColumnType<infer S, infer I, infer U>
  ? ColumnType<S, I | undefined, U>
  : ColumnType<T, T | undefined, T>;
export type GeneratedAlways<T> = ColumnType<T, never, never>;
export type ArrayType<T> = T[];
/** BIGINT: parsed to bigint (money in minor units). */
export type Int8 = ColumnType<bigint, bigint | number | string, bigint | number | string>;
/** NUMERIC: kept as a decimal string, never a float. */
export type Numeric = ColumnType<string, string | number, string | number>;
export type Timestamp = ColumnType<Date, Date | string, Date | string>;
export type Json = ColumnType<JsonValue, JsonValue | string, JsonValue | string>;
export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };
`;

export async function generateSchema(client: MigrationClient): Promise<string> {
  const rows = await client.query<ColumnRow>(`
    SELECT c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, c.is_identity, c.is_generated
    FROM information_schema.columns c
    JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
    ORDER BY c.table_name, c.ordinal_position`);

  const tables = new Map<string, ColumnRow[]>();
  for (const r of rows) tables.set(r.table_name, [...(tables.get(r.table_name) ?? []), r]);

  const out: string[] = [HEADER];
  for (const [table, cols] of tables) {
    out.push(`export interface ${pascal(table)} {`);
    for (const c of cols) {
      let type = tsType(c.udt_name);
      if (c.is_nullable === "YES") type = `${type} | null`;
      if (c.is_generated === "ALWAYS") type = `GeneratedAlways<${type}>`;
      else if (c.column_default !== null || c.is_identity === "YES") type = `Generated<${type}>`;
      out.push(`  ${c.column_name}: ${type};`);
    }
    out.push("}\n");
  }
  out.push("export interface DB {");
  for (const table of tables.keys()) out.push(`  ${table}: ${pascal(table)};`);
  out.push("}\n");
  return out.join("\n");
}
