#!/usr/bin/env node
/**
 * Builds the Mizan icon set from icons/manifest.json:
 *   icons/svg/<name>.svg   restyled Lucide glyphs (stroke 1.75, currentColor, 24 grid)
 *   icons/sprite.svg       <symbol id="mz-<name>"> sprite for plain HTML and email-safe use
 *   icons/index.ts         typed metadata: IconName, labels (EN/AR), group, RTL flip
 *   icons/react.tsx        <Icon name="orders" /> backed by lucide-react (tree-shaken imports)
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const lucideDir = join(dirname(require.resolve("lucide-static/package.json")), "icons");
const M = JSON.parse(readFileSync(join(root, "icons/manifest.json"), "utf8"));
const svgDir = join(root, "icons/svg");
rmSync(svgDir, { recursive: true, force: true }); mkdirSync(svgDir, { recursive: true });

const pascal = (s) => s.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const inner = (svg) => svg.replace(/<!--.*?-->/gs, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();

const symbols = [];
for (const icon of M.icons) {
  const src = readFileSync(join(lucideDir, `${icon.lucide}.svg`), "utf8");
  const body = inner(src).replace(/\n\s*/g, "");
  const flip = icon.rtlFlip ? ' data-rtl-flip="true"' : "";
  writeFileSync(join(svgDir, `${icon.name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${M.stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"${flip}>${body}</svg>\n`);
  symbols.push(`<symbol id="mz-${icon.name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${M.stroke}" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`);
}
writeFileSync(join(root, "icons/sprite.svg"), `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols.join("\n")}\n</svg>\n`);

const meta = M.icons.map((i) => `  ${JSON.stringify(i.name)}: { group: ${JSON.stringify(i.group)}, en: ${JSON.stringify(i.en)}, ar: ${JSON.stringify(i.ar)}, rtlFlip: ${i.rtlFlip}, lucide: ${JSON.stringify(pascal(i.lucide))} },`).join("\n");
writeFileSync(join(root, "icons/index.ts"), `/* Generated by scripts/build-icons.mjs from icons/manifest.json. Do not edit. */
export const ICONS = {
${meta}
} as const;

export type IconName = keyof typeof ICONS;
export type IconGroup = (typeof ICONS)[IconName]["group"];
export const ICON_STROKE = ${M.stroke};
export const iconNames = Object.keys(ICONS) as IconName[];
/** Accessible label in the UI language. */
export const iconLabel = (name: IconName, lang: "ar" | "en") => ICONS[name][lang];
`);

const lucideNames = [...new Set(M.icons.map((i) => pascal(i.lucide)))].sort();
writeFileSync(join(root, "icons/react.tsx"), `/* Generated by scripts/build-icons.mjs from icons/manifest.json. Do not edit. */
import type { LucideIcon, LucideProps } from "lucide-react";
import { ${lucideNames.join(", ")} } from "lucide-react";
import { ICONS, ICON_STROKE, type IconName } from "./index";

const MAP: Record<IconName, LucideIcon> = {
${M.icons.map((i) => `  ${JSON.stringify(i.name)}: ${pascal(i.lucide)},`).join("\n")}
};

export interface IconProps extends Omit<LucideProps, "ref"> {
  name: IconName;
  /** Accessible label. Omit for decorative icons next to visible text. */
  label?: string;
}

/**
 * Mizan icon. Size defaults to 18 (UI) — use 16 in dense tables, 20–24 in empty states.
 * Directional icons flip automatically in RTL (class "mz-rtl-flip" + CSS in base.css).
 */
export function Icon({ name, label, size = 18, strokeWidth = ICON_STROKE, className, ...rest }: IconProps) {
  const C = MAP[name];
  const cls = [ICONS[name].rtlFlip ? "mz-rtl-flip" : "", className].filter(Boolean).join(" ") || undefined;
  return <C size={size} strokeWidth={strokeWidth} className={cls} aria-hidden={label ? undefined : true} aria-label={label} role={label ? "img" : undefined} {...rest} />;
}
`);
console.log(`icons built: ${M.icons.length}`);
